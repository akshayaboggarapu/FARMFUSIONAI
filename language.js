// Helper: Get active language from localStorage or default to 'en'
function getCurrentLang() {
  return localStorage.getItem('farmfusion_lang') || 'en';
}

function setLanguage(lang) {
  if (['en', 'te', 'hi'].includes(lang)) {
    localStorage.setItem('farmfusion_lang', lang);
    applyLanguageTranslations(lang);
  }
}

// Function to replace all elements with data-i18n attribute
function applyLanguageTranslations(lang) {
  const dict = FF_LANG[lang] || FF_LANG.en;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
        el.value = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Also update placeholders if attribute exists
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // Sync any language selector dropdown on page
  document.querySelectorAll('.lang-select-input').forEach((sel) => {
    sel.value = lang;
  });
}
